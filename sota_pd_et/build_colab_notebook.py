def cell(kind, source, identifier):
    source = textwrap.dedent(source).strip() + "\n"
    result = {"cell_type": kind, "id": identifier, "metadata": {},
              "source": source.splitlines(keepends=True)}
    if kind == "code":
        ast.parse(source, filename=f"<notebook:{identifier}>")
        result.update(execution_count=None, outputs=[])
    return result


def embedded_file(relative):
    """Keep embedded source readable and identical to the corresponding module."""
    source = (PROJECT / relative).read_text(encoding="utf-8")
    if "'''" in source or source.endswith("\\"):
        raise ValueError(f"Choose another source quoting convention for {relative}.")
    content = (f"# Embedded file: {relative}\n"
               f"embedded_source = r'''{source}'''\n"
               f"destination = WORK / {relative!r}\n"
               "destination.parent.mkdir(parents=True, exist_ok=True)\n"
               "destination.write_text(embedded_source, encoding='utf-8')\n"
               "print('Prepared:', destination.relative_to(WORK))\n")
    result = cell("code", content, relative.replace("/", "-").replace(".", "-"))
    result["metadata"]["cellView"] = "form"
    return result


